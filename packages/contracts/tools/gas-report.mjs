#!/usr/bin/env node
// Regenerates docs/GAS.md from hardhat-gas-reporter.
//
//   npm run gas:report --workspace @trustchain/contracts
//
// A small wrapper rather than an inline env assignment, because `REPORT_GAS=true cmd`
// is not portable to Windows shells and adding cross-env for one script is not worth a
// dependency.

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const contractsDir = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const repoRoot = path.resolve(contractsDir, "..", "..");
const rawReport = path.join(contractsDir, "gas-report.txt");
const outputFile = path.join(repoRoot, "docs", "GAS.md");

rmSync(rawReport, { force: true });

const hardhatBin = path.join(
  repoRoot,
  "node_modules",
  "hardhat",
  "internal",
  "cli",
  "bootstrap.js",
);
if (!existsSync(hardhatBin)) {
  throw new Error(`hardhat CLI not found at ${hardhatBin} — run npm install first`);
}

const result = spawnSync(process.execPath, [hardhatBin, "test"], {
  cwd: contractsDir,
  env: { ...process.env, REPORT_GAS: "true", GAS_REPORT_FILE: rawReport },
  stdio: "inherit",
});

if (result.status !== 0) {
  throw new Error("test run failed; gas report not regenerated");
}
if (!existsSync(rawReport)) {
  throw new Error(`gas reporter produced no output at ${rawReport}`);
}

const table = readFileSync(rawReport, "utf8").trimEnd();
rmSync(rawReport, { force: true });

const generated = new Date().toISOString().slice(0, 10);

const markdown = `# Gas Report

Generated by \`npm run gas:report --workspace @trustchain/contracts\` on ${generated}.
Figures come from the Hardhat test suite, so they reflect real call paths rather than
synthetic benchmarks. Test doubles under \`contracts/mocks/\` are excluded.

Regenerate after any change that could move these numbers; a stale table is worse than
no table.

\`\`\`
${table}
\`\`\`

## Reading this

- **Deployment cost** matters once per contract. All five are UUPS proxies except
  \`AuditTrail\`, which is deliberately non-upgradeable, so its implementation cost is
  paid once and never again.
- **Method costs** are what users and administrators actually pay. \`mint\` and
  \`registerDID\` sit on the critical demo path.
- Costs rose slightly when the audit trail was wired in (P1.4b): every mutating call now
  also appends an entry. That is the price of a tamper-proof audit log, and it is charged
  only when a trail is configured.
`;

mkdirSync(path.dirname(outputFile), { recursive: true });
writeFileSync(outputFile, markdown);

console.log(`gas report written to ${path.relative(repoRoot, outputFile)}`);
