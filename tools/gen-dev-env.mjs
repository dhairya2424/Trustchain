#!/usr/bin/env node
/**
 * Generates `packages/backend/.env` for a local run.
 *
 *   node tools/gen-dev-env.mjs
 *
 * Every secret is generated here, on this machine, and written only to a gitignored file.
 * Nothing is prompted for, pasted, or echoed to the terminal — a key that appears in a
 * terminal is a key in a scrollback buffer, a shell history and possibly a screen share.
 *
 * Contract addresses are read from the deployment record rather than typed, so the file
 * cannot drift from the chain it points at.
 *
 * LOCAL ONLY. It writes `NODE_ENV=development` and wires the local relayer and pinner. It
 * refuses to overwrite an existing .env, because clobbering a file that might hold real
 * credentials is not recoverable.
 */
import { generateKeyPairSync, randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const envPath = path.join(repoRoot, "packages", "backend", ".env");
const deploymentPath = path.join(
  repoRoot,
  "packages",
  "contracts",
  "deployments",
  "localhost.json",
);

/** Cloudflare's documented always-passes test secret. Not a credential. */
const TURNSTILE_TEST_SECRET = "1x0000000000000000000000000000000AA";

function rsaPair() {
  const { privateKey, publicKey } = generateKeyPairSync("rsa", { modulusLength: 2048 });
  // Newlines are escaped so each key occupies one line; the server un-escapes them.
  const asLine = (pem) => pem.toString().trim().replace(/\n/g, "\\n");
  return {
    privateKey: asLine(privateKey.export({ type: "pkcs8", format: "pem" })),
    publicKey: asLine(publicKey.export({ type: "spki", format: "pem" })),
  };
}

function main() {
  if (existsSync(envPath)) {
    console.error(
      `refusing to overwrite ${path.relative(repoRoot, envPath)}\n` +
        `delete it first if you really want a fresh one`,
    );
    process.exitCode = 1;
    return;
  }

  if (!existsSync(deploymentPath)) {
    console.error(
      `no deployment record at ${path.relative(repoRoot, deploymentPath)}\n` +
        `run: npm run deploy:local`,
    );
    process.exitCode = 1;
    return;
  }

  const deployment = JSON.parse(readFileSync(deploymentPath, "utf8"));
  const at = (name) => {
    const address = deployment.contracts?.[name]?.address;
    if (!address) throw new Error(`deployment record has no address for ${name}`);
    return address;
  };

  const session = rsaPair();
  const credential = rsaPair();

  const lines = [
    "# Generated by tools/gen-dev-env.mjs for LOCAL DEVELOPMENT ONLY.",
    "# Every key here was generated on this machine and is gitignored. Do not reuse any of",
    "# it anywhere real, and do not commit this file.",
    "",
    "NODE_ENV=development",
    "PORT=4000",
    "LOG_LEVEL=debug",
    "CORS_ORIGIN=http://localhost:5173",
    "",
    // Ports follow docker-compose, which allows overrides. A pre-existing native service
    // on the default port will shadow the container and answer as a different (often much
    // older) server, so these are read from the environment rather than assumed.
    `DATABASE_URL=postgresql://trustchain:trustchain_dev_only@localhost:${process.env.POSTGRES_PORT ?? "5432"}/trustchain`, // secrets-scan:allow docker-compose dev default
    `REDIS_URL=redis://localhost:${process.env.REDIS_PORT ?? "6379"}`,
    "",
    `JWT_PRIVATE_KEY=${session.privateKey}`,
    `JWT_PUBLIC_KEY=${session.publicKey}`,
    "JWT_ACCESS_TTL_SECONDS=900",
    "SESSION_COOKIE_NAME=trustchain_session",
    "SESSION_COOKIE_DOMAIN=localhost",
    "",
    "SIWE_DOMAIN=localhost:5173",
    "SIWE_ORIGIN=http://localhost:5173",
    "SIWE_NONCE_TTL_SECONDS=300",
    "",
    `FIELD_ENCRYPTION_KEY=${randomBytes(32).toString("base64")}`,
    "",
    `CREDENTIAL_PRIVATE_KEY=${credential.privateKey}`,
    `CREDENTIAL_PUBLIC_KEY=${credential.publicKey}`,
    "CREDENTIAL_ISSUER_ID=trustchain",
    "",
    "CHAIN_RPC_URL=http://127.0.0.1:8545",
    "CHAIN_ID=31337",
    "",
    `ROLE_ACCESS_CONTROL_ADDRESS=${at("RoleAccessControl")}`,
    `DID_REGISTRY_ADDRESS=${at("DIDRegistry")}`,
    `ASSET_REGISTRY_ADDRESS=${at("AssetRegistry")}`,
    `CREDENTIAL_REGISTRY_ADDRESS=${at("CredentialRegistry")}`,
    `AUDIT_TRAIL_ADDRESS=${at("AuditTrail")}`,
    "",
    "# No subgraph runs locally, so this address is unreachable on purpose: the audit API",
    "# falls back to reading the chain directly, which is the path worth exercising here.",
    "SUBGRAPH_URL=http://127.0.0.1:8000/subgraphs/name/trustchain",
    `AUDIT_TRAIL_DEPLOYMENT_BLOCK=${deployment.blockNumber ?? 0}`,
    "AUDIT_MAX_EXPORT_ROWS=50000",
    "",
    "# Unused locally — the local pinner stands in — but the schema requires them.",
    "PINATA_JWT=unused-locally",
    "PINATA_GATEWAY=http://localhost:8080",
    "",
    `TURNSTILE_SECRET_KEY=${TURNSTILE_TEST_SECRET}`,
    "",
    "# Raised for local development so an end-to-end run is not throttled by its own",
    "# breadth. The production defaults (5 per minute, block after 10 failures) are in",
    "# config/env.ts and apply whenever these are absent. tools/e2e-flow.mjs proves the",
    "# limiter still fires by deliberately exhausting it.",
    "AUTH_RATE_LIMIT_POINTS=60",
    "AUTH_RATE_LIMIT_WINDOW_SECONDS=60",
    "AUTH_FAILURE_THRESHOLD=80",
    "",
    "# Self-hosted OpenZeppelin Relayer. The signing key lives in that service, never here.",
    "# RELAYER_API_KEY is the API_KEY from infra/relayer/.env — fill it in after generating.",
    "RELAYER_URL=http://localhost:8081",
    "RELAYER_ID=trustchain-amoy",
    "RELAYER_API_KEY=",
    "RELAYER_SPEED=average",
    "",
    "# Filesystem stand-in for IPFS. Independent of the relayer: set PINATA_JWT to a real",
    "# credential to pin for real while still signing against a local chain.",
    "DEV_IPFS_DIR=.local-ipfs",
    "",
  ];

  writeFileSync(envPath, lines.join("\n"), { mode: 0o600 });

  console.log(`wrote ${path.relative(repoRoot, envPath)}`);
  console.log("  session and credential RSA keypairs: generated");
  console.log("  field encryption key: generated");
  console.log("  contract addresses: read from deployments/localhost.json");
  console.log("  relayer: Hardhat account #1 (public test key, granted MANAGER by the seed)");
}

main();
