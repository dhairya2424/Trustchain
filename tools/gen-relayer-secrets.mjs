#!/usr/bin/env node
/**
 * Generates the secrets the OpenZeppelin Relayer service needs, into `infra/relayer/.env`.
 *
 *   node tools/gen-relayer-secrets.mjs
 *
 * Three values, all generated here and never printed:
 *
 *   KEYSTORE_PASSPHRASE  decrypts the local signer keystore
 *   API_KEY              the bearer credential the backend presents
 *   WEBHOOK_SIGNING_KEY  signs the relayer's outbound notifications
 *
 * The passphrase satisfies the relayer's documented complexity rule (12+ characters, with
 * upper, lower, digit and special) by construction rather than by retry, so there is no
 * loop that could terminate on a weak value.
 *
 * Nothing is echoed to the terminal. A secret printed to stdout is a secret in a scrollback
 * buffer, a shell history file, and any screen recording of the session — and this one
 * decrypts a signing key.
 *
 * Refuses to overwrite: regenerating the passphrase for an existing keystore would leave a
 * key file nothing can open.
 */
import { randomInt, randomUUID } from "node:crypto";
import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const relayerDir = path.join(repoRoot, "infra", "relayer");
const envPath = path.join(relayerDir, ".env");

const UPPER = "ABCDEFGHJKLMNPQRSTUVWXYZ";
const LOWER = "abcdefghijkmnopqrstuvwxyz";
const DIGIT = "23456789";
const SPECIAL = "!@#$%^&*_-+=";
const ALL = UPPER + LOWER + DIGIT + SPECIAL;

const pick = (alphabet) => alphabet[randomInt(0, alphabet.length)];

/** 32 characters, guaranteed to contain one of each required class, then shuffled. */
function passphrase() {
  const required = [pick(UPPER), pick(LOWER), pick(DIGIT), pick(SPECIAL)];
  const rest = Array.from({ length: 28 }, () => pick(ALL));
  const chars = [...required, ...rest];

  // Fisher-Yates with a CSPRNG, so the required characters are not always in front.
  for (let i = chars.length - 1; i > 0; i -= 1) {
    const j = randomInt(0, i + 1);
    [chars[i], chars[j]] = [chars[j], chars[i]];
  }

  return chars.join("");
}

function main() {
  if (existsSync(envPath)) {
    console.error(
      `refusing to overwrite ${path.relative(repoRoot, envPath)}\n` +
        `regenerating the passphrase would orphan the existing keystore — delete both first`,
    );
    process.exitCode = 1;
    return;
  }

  mkdirSync(path.join(relayerDir, "config", "keys"), { recursive: true });

  const lines = [
    "# Generated by tools/gen-relayer-secrets.mjs. LOCAL DEVELOPMENT ONLY.",
    "# Gitignored. The passphrase below decrypts config/keys/local-signer.json — losing it",
    "# means losing the signer, and leaking it means leaking the key.",
    "",
    `KEYSTORE_PASSPHRASE=${passphrase()}`,
    `API_KEY=${randomUUID()}`,
    `WEBHOOK_SIGNING_KEY=${randomUUID()}`,
    "",
    "# Redis used by the relayer for its transaction queue. Shares our container on 6380;",
    "# database 1 keeps its keyspace clear of the API's sessions and rate-limit counters.",
    "REDIS_URL=redis://redis:6379/1",
    "",
    `RUST_LOG=info`,
    "",
  ];

  writeFileSync(envPath, lines.join("\n"), { mode: 0o600 });

  console.log(`wrote ${path.relative(repoRoot, envPath)}`);
  console.log("  KEYSTORE_PASSPHRASE, API_KEY, WEBHOOK_SIGNING_KEY: generated, not printed");
}

main();
